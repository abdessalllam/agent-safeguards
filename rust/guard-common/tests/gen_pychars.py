#!/usr/bin/env python3
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "pychars_tables.rs"


def ranges(test):
    found = []
    start = None
    for code in range(0x110000):
        hit = not 0xD800 <= code <= 0xDFFF and test(chr(code))
        if hit and start is None:
            start = code
        if not hit and start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def table(name, items):
    body = ", ".join("(0x%X, 0x%X)" % item for item in items)
    return "pub static %s: &[(u32, u32)] = &[%s];\n" % (name, body)


zeros = []
for code in range(0x110000):
    if 0xD800 <= code <= 0xDFFF:
        continue
    character = chr(code)
    if unicodedata.category(character) == "Nd" and unicodedata.decimal(character) == 0:
        zeros.append(code)
text = "// Generated by tests/gen_pychars.py from Python %s (Unicode %s).\n" % (sys.version.split()[0], unicodedata.unidata_version)
text += table("ALPHA", ranges(str.isalpha))
text += table("DECIMAL", ranges(str.isdecimal))
text += table("DIGIT", ranges(str.isdigit))
text += table("NUMERIC", ranges(str.isnumeric))
text += table("SPACE", ranges(str.isspace))
text += "pub static DECIMAL_ZEROS: &[u32] = &[%s];\n" % ", ".join("0x%X" % code for code in zeros)
OUT.write_text(text)
print("wrote", OUT, len(text))
