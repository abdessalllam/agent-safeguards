const WALK_ENTRIES: usize = 4000;
const WALK_TIME: Duration = Duration::from_millis(800);
const TOTAL_TIME: Duration = Duration::from_millis(3000);
const MAX_CANDIDATES: usize = 40;
const SOURCE_FILES: usize = 400;
const GLOB_MATCHES: usize = 200;
const SOURCE_BYTES: usize = 32 * 1024 * 1024;
const FIRST_WINDOW: Duration = Duration::from_secs(60);
const SKIP_DIRS: [&str; 10] = [
    "node_modules",
    "target",
    "dist",
    "build",
    "out",
    "venv",
    "vendor",
    "coverage",
    "Pods",
    "__pycache__",
];
const GENERATED: [&str; 4] = ["generated", "do not edit", "auto-generated", "autogenerated"];
const IMPORTING: &[&str] = &[
    "merge", "pull", "checkout", "switch", "restore", "reset", "rebase", "cherry-pick", "revert", "stash",
];
const READ_ONLY: &[&str] = &[
    "add", "commit", "status", "diff", "log", "show", "branch", "tag", "remote", "rev-parse", "rev-list", "ls-files",
    "ls-tree", "cat-file", "merge-base", "describe", "fetch", "mv", "rm",
];
const BENIGN_CONFIG: &[&str] = &[
    "user.name",
    "user.email",
    "core.editor",
    "core.pager",
    "merge.ff",
    "pull.rebase",
    "pull.ff",
    "commit.gpgsign",
    "rerere.enabled",
    "advice.detachedhead",
    "init.defaultbranch",
    "color.ui",
    "core.quotepath",
];
const HARMLESS: &[&str] = &[
    "cd", "pwd", "true", "echo", "ls", "head", "tail", "wc", "grep", "rg", "cut", "uniq", "cat", "test", "[", "sleep",
];

enum Head {
    Found(String),
    Missing,
    Unavailable,
}

pub fn judge_command(payload: &Map<String, Value>, ledger: &Ledger) -> Verdict {
    let deadline = Instant::now() + TOTAL_TIME;
    if payload.get("cwd").and_then(Value::as_str).is_none() {
        return Verdict::Allow;
    }
    let cwd = crate::base_of(payload);
    if !cwd.is_dir() {
        return Verdict::Allow;
    }
    let command = command_of(payload);
    let key = identity(&cwd);
    let since = payload
        .get("tool_use_id")
        .and_then(Value::as_str)
        .and_then(|id| ledger.take_start(id))
        .or_else(|| ledger.last_check(&key))
        .or_else(|| SystemTime::now().checked_sub(FIRST_WINDOW))
        .unwrap_or(SystemTime::UNIX_EPOCH);
    ledger.mark_check(&key);
    let importing = imports_history(command);
    let mut files = command_paths(command, &cwd);
    let room = MAX_CANDIDATES.saturating_sub(files.len());
    files.extend(walk_files(&cwd, room, &|meta| modified_since(meta, since)));
    let mut seen: HashSet<PathBuf> = HashSet::new();
    let mut changes: Vec<Change> = Vec::new();
    for file in files {
        if Instant::now() >= deadline {
            break;
        }
        if !seen.insert(file.clone()) {
            continue;
        }
        if importing {
            rebaseline(&file, since, ledger);
            continue;
        }
        if let Some(change) = change_for(&file, since, ledger, deadline) {
            changes.push(change);
        }
    }
    let mut verdict = evaluate_after(&changes);
    if verdict.is_some() {
        drop_marked(&mut changes, &cwd);
        drop_copies(&mut changes, command, &cwd, since, ledger);
        verdict = evaluate_after(&changes);
    }
    match verdict {
        Some(reason) => Verdict::Deny(reason),
        None => Verdict::Allow,
    }
}

fn command_of(payload: &Map<String, Value>) -> &str {
    payload
        .get("tool_input")
        .and_then(|input| input.get("command"))
        .and_then(Value::as_str)
        .unwrap_or("")
}

pub fn refresh_named(payload: &Map<String, Value>, ledger: &Ledger) {
    let cwd = crate::base_of(payload);
    let mut targets: Vec<PathBuf> = Vec::new();
    for token in command_tokens(command_of(payload), &cwd) {
        for file in source_files(&token) {
            if !targets.contains(&file) {
                targets.push(file);
            }
        }
    }
    for path in targets {
        let name = path.to_string_lossy().into_owned();
        let Some(lang) = language_for(&name) else {
            continue;
        };
        let id = identity(&path);
        if ledger.read(&id).is_none() {
            continue;
        }
        let Some(current) = read_old(&path) else {
            continue;
        };
        let comments = comment_lines(&current, lang);
        let state = seen_of(&current, &comments);
        if !ledger.knows(&id, state) {
            ledger.rebaseline(&id, comments, state);
        }
    }
}

fn home() -> Option<PathBuf> {
    let path = PathBuf::from(std::env::var("HOME").ok()?);
    path.is_absolute().then_some(path)
}

fn wildcard_match(pattern: &[char], name: &[char]) -> bool {
    let (mut p, mut n) = (0usize, 0usize);
    let mut star: Option<(usize, usize)> = None;
    while n < name.len() {
        match pattern.get(p) {
            Some('*') => {
                star = Some((p, n));
                p += 1;
            }
            Some('?') => {
                p += 1;
                n += 1;
            }
            Some(c) if Some(c) == name.get(n) => {
                p += 1;
                n += 1;
            }
            _ => match star {
                Some((star_at, matched)) => {
                    p = star_at + 1;
                    n = matched + 1;
                    star = Some((star_at, matched + 1));
                }
                None => return false,
            },
        }
    }
    while pattern.get(p) == Some(&'*') {
        p += 1;
    }
    p == pattern.len()
}

fn expand_glob(cwd: &Path, word: &str) -> Vec<PathBuf> {
    let (folder, last) = match word.rsplit_once('/') {
        Some((folder, last)) => (folder, last),
        None => ("", word),
    };
    if folder.contains(['*', '?']) {
        return Vec::new();
    }
    let dir = if folder.is_empty() { cwd.to_path_buf() } else { resolve(cwd, folder) };
    let pattern: Vec<char> = last.chars().collect();
    let Ok(entries) = fs::read_dir(&dir) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    for entry in entries.flatten() {
        let name: Vec<char> = entry.file_name().to_string_lossy().chars().collect();
        if name.first() != Some(&'.') && wildcard_match(&pattern, &name) {
            out.push(entry.path());
            if out.len() >= GLOB_MATCHES {
                break;
            }
        }
    }
    out
}

fn command_words(command: &str) -> Vec<String> {
    let mut words: Vec<String> = Vec::new();
    if let Some(parts) = segments(command) {
        for part in parts {
            words.extend(part);
        }
    }
    let separators = |c: char| c.is_whitespace() || "\"'`<>|;&()=,{}[]".contains(c);
    words.extend(command.split(separators).map(str::to_owned));
    let mut seen: HashSet<String> = HashSet::new();
    words.retain(|word| seen.insert(word.clone()));
    words
}

fn command_tokens(command: &str, cwd: &Path) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    for word in command_words(command) {
        if word.len() < 2 || word.chars().all(|c| c == '.') {
            continue;
        }
        if word.contains(['*', '?']) {
            out.extend(expand_glob(cwd, &word));
        } else {
            let path = match (word.strip_prefix("~/"), home()) {
                (Some(rest), Some(root)) => root.join(rest),
                _ => resolve(cwd, &word),
            };
            if path.exists() {
                out.push(path);
            }
        }
        if out.len() >= MAX_CANDIDATES {
            break;
        }
    }
    out
}

fn command_paths(command: &str, cwd: &Path) -> Vec<PathBuf> {
    command_tokens(command, cwd)
        .into_iter()
        .filter(|path| path.is_file() && language_for(&path.to_string_lossy()).is_some())
        .collect()
}

fn modified_since(meta: &fs::Metadata, since: SystemTime) -> bool {
    meta.modified().is_ok_and(|modified| modified >= since)
}

fn walk_files(root: &Path, limit: usize, keep: &dyn Fn(&fs::Metadata) -> bool) -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = Vec::new();
    if root.parent().is_none() || home().as_deref() == Some(root) {
        return files;
    }
    let start = Instant::now();
    let mut stack = vec![root.to_path_buf()];
    let mut visited = 0usize;
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            visited = visited.saturating_add(1);
            if visited > WALK_ENTRIES || start.elapsed() > WALK_TIME || files.len() >= limit {
                return files;
            }
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if name.starts_with('.') {
                continue;
            }
            let Ok(kind) = entry.file_type() else {
                continue;
            };
            if kind.is_dir() {
                if !SKIP_DIRS.iter().any(|skip| *skip == &*name) {
                    stack.push(entry.path());
                }
            } else if kind.is_file()
                && language_for(&name).is_some()
                && entry.metadata().is_ok_and(|meta| keep(&meta))
            {
                files.push(entry.path());
            }
        }
    }
    files
}

fn source_files(path: &Path) -> Vec<PathBuf> {
    if path.is_file() {
        return if language_for(&path.to_string_lossy()).is_some() {
            vec![path.to_path_buf()]
        } else {
            Vec::new()
        };
    }
    if path.is_dir() {
        return walk_files(path, SOURCE_FILES, &|_| true);
    }
    Vec::new()
}

fn drop_copies(changes: &mut Vec<Change>, command: &str, cwd: &Path, since: SystemTime, ledger: &Ledger) {
    let mut known: HashSet<u64> = HashSet::new();
    let mut budget = SOURCE_BYTES;
    let mut roots = command_tokens(command, cwd);
    if command_words(command).iter().any(|word| word == ".") {
        roots.push(cwd.to_path_buf());
    }
    'roots: for token in roots {
        for file in source_files(&token) {
            if changed_since(&file, since) {
                continue;
            }
            let Some(text) = read_old(&file) else {
                continue;
            };
            if text.len() > budget {
                break 'roots;
            }
            budget = budget.saturating_sub(text.len());
            known.insert(content_hash(&text));
        }
    }
    let mut kept: Vec<Change> = Vec::new();
    for change in changes.drain(..) {
        if !known.contains(&content_hash(&change.new)) {
            kept.push(change);
            continue;
        }
        if let Some(lang) = language_for(&change.file) {
            let comments = comment_lines(&change.new, lang);
            let state = seen_of(&change.new, &comments);
            ledger.rebaseline(&identity(Path::new(&change.file)), comments, state);
        }
    }
    *changes = kept;
}

fn absent(stderr: &str, dir: &Path) -> bool {
    let known = ["exists on disk, but not in", "does not exist in", "invalid object name 'HEAD'"];
    known.iter().any(|message| stderr.contains(message))
        || (stderr.contains("not a git repository")
            && !dir.ancestors().any(|folder| folder.join(".git").exists()))
}

fn head_text(path: &Path, deadline: Instant) -> Head {
    let (Some(dir), Some(name)) = (path.parent(), path.file_name().and_then(|name| name.to_str())) else {
        return Head::Unavailable;
    };
    if !inside_repository(dir) {
        return Head::Missing;
    }
    let spec = format!("HEAD:./{name}");
    let Some(ran) = run_git(dir, &["show", &spec], None, deadline) else {
        return Head::Unavailable;
    };
    if ran.stdout.len() as u64 > MAX_OLD_FILE {
        return Head::Unavailable;
    }
    if ran.success {
        return Head::Found(String::from_utf8_lossy(&ran.stdout).into_owned());
    }
    if absent(&ran.stderr, dir) {
        Head::Missing
    } else {
        Head::Unavailable
    }
}

#[cfg(unix)]
fn status_changed(meta: &fs::Metadata, since: SystemTime) -> bool {
    use std::os::unix::fs::MetadataExt;
    let Ok(secs) = u64::try_from(meta.ctime()) else {
        return false;
    };
    let nanos = u32::try_from(meta.ctime_nsec()).unwrap_or(0);
    SystemTime::UNIX_EPOCH + Duration::new(secs, nanos) >= since
}

#[cfg(not(unix))]
fn status_changed(_meta: &fs::Metadata, _since: SystemTime) -> bool {
    false
}

fn changed_since(path: &Path, since: SystemTime) -> bool {
    let Ok(meta) = fs::metadata(path) else {
        return false;
    };
    modified_since(&meta, since) || status_changed(&meta, since)
}

fn born_since(path: &Path, since: SystemTime) -> bool {
    fs::metadata(path)
        .and_then(|meta| meta.created())
        .is_ok_and(|created| created >= since)
}

fn looks_generated(text: &str) -> bool {
    let head: String = text.lines().take(5).collect::<Vec<&str>>().join("\n").to_lowercase();
    GENERATED.iter().any(|marker| head.contains(marker))
}

fn rebaseline(path: &Path, since: SystemTime, ledger: &Ledger) {
    let name = path.to_string_lossy();
    let Some(lang) = language_for(&name) else {
        return;
    };
    let Some(current) = read_old(path) else {
        return;
    };
    let comments = comment_lines(&current, lang);
    let state = seen_of(&current, &comments);
    let id = identity(path);
    if changed_since(path, since) && !ledger.knows(&id, state) {
        ledger.rebaseline(&id, comments, state);
    }
}

fn change_for(path: &Path, since: SystemTime, ledger: &Ledger, deadline: Instant) -> Option<Change> {
    let name = path.to_string_lossy().into_owned();
    let lang = language_for(&name)?;
    let current = read_old(path)?;
    if looks_generated(&current) {
        return None;
    }
    let id = identity(path);
    let comments = comment_lines(&current, lang);
    let state = seen_of(&current, &comments);
    let recorded = ledger.read(&id);
    if !changed_since(path, since) {
        if recorded.is_none() {
            ledger.baseline_for(&id, state, || comments.clone());
        }
        return None;
    }
    let change = match recorded {
        Some(baseline) => Some(judged(name, current, baseline)),
        None => match head_text(path, deadline) {
            Head::Found(text) => {
                let baseline = ledger.baseline_for(&id, state, || comment_lines(&text, lang));
                Some(judged(name, current, baseline))
            }
            Head::Unavailable => None,
            Head::Missing if born_since(path, since) => {
                ledger.baseline_for(&id, state, Vec::new);
                Some(Change::whole(name, String::new(), current))
            }
            Head::Missing => {
                ledger.baseline_for(&id, state, || comments.clone());
                None
            }
        },
    };
    ledger.accept(&id, &[state]);
    change
}

fn judged(name: String, current: String, baseline: Vec<String>) -> Change {
    Change {
        file: name,
        old: String::new(),
        new: current,
        baseline: Some(baseline),
        partial: false,
        origin: None,
        carry: 0,
    }
}

fn segments(command: &str) -> Option<Vec<Vec<String>>> {
    let mut out: Vec<Vec<String>> = Vec::new();
    let mut words: Vec<String> = Vec::new();
    let mut word = String::new();
    let mut open = false;
    let mut quote: Option<char> = None;
    let mut chars = command.chars().peekable();
    while let Some(c) = chars.next() {
        if let Some(q) = quote {
            if c == q {
                quote = None;
                continue;
            }
            if q == '"' {
                if c == '\\' {
                    if let Some(next) = chars.next() {
                        word.push(next);
                    }
                    continue;
                }
                if c == '`' || (c == '$' && chars.peek() == Some(&'(')) {
                    return None;
                }
            }
            word.push(c);
            continue;
        }
        match c {
            '\'' | '"' => {
                quote = Some(c);
                open = true;
            }
            '\\' => {
                if let Some(next) = chars.next() {
                    word.push(next);
                    open = true;
                }
            }
            '>' | '<' | '`' => return None,
            '$' if chars.peek() == Some(&'(') => return None,
            '\n' | ';' | '&' | '|' => {
                if open {
                    words.push(std::mem::take(&mut word));
                    open = false;
                }
                if matches!(c, '&' | '|') && chars.peek() == Some(&c) {
                    chars.next();
                }
                if !words.is_empty() {
                    out.push(std::mem::take(&mut words));
                }
            }
            space if space.is_whitespace() => {
                if open {
                    words.push(std::mem::take(&mut word));
                    open = false;
                }
            }
            other => {
                word.push(other);
                open = true;
            }
        }
    }
    if quote.is_some() {
        return None;
    }
    if open {
        words.push(word);
    }
    if !words.is_empty() {
        out.push(words);
    }
    Some(out)
}

fn git_segment(words: &[String]) -> Option<bool> {
    if words
        .iter()
        .any(|word| matches!(word.as_str(), "--exec" | "-x") || word.starts_with("--exec="))
    {
        return None;
    }
    let mut at = 0usize;
    while let Some(word) = words.get(at) {
        match word.as_str() {
            "-C" => at = at.saturating_add(2),
            "-c" => {
                let setting = words.get(at.saturating_add(1))?;
                let key = setting.split('=').next().unwrap_or("").to_ascii_lowercase();
                if !BENIGN_CONFIG.contains(&key.as_str()) {
                    return None;
                }
                at = at.saturating_add(2);
            }
            "--no-pager" | "-P" | "-p" | "--paginate" | "--no-optional-locks" => at = at.saturating_add(1),
            option if option.starts_with('-') => return None,
            subcommand => {
                if IMPORTING.contains(&subcommand) {
                    return Some(true);
                }
                return READ_ONLY.contains(&subcommand).then_some(false);
            }
        }
    }
    None
}

fn imports_history(command: &str) -> bool {
    let Some(parts) = segments(command) else {
        return false;
    };
    let mut importing = false;
    for mut words in parts {
        while words
            .first()
            .is_some_and(|word| word.contains('=') && !word.starts_with('=') && !word.contains('/'))
        {
            words.remove(0);
        }
        let Some((first, rest)) = words.split_first() else {
            continue;
        };
        if first == "git" {
            match git_segment(rest) {
                Some(true) => importing = true,
                Some(false) => {}
                None => return false,
            }
        } else if !HARMLESS.contains(&first.as_str()) {
            return false;
        }
    }
    importing
}

#[cfg(test)]
mod tests {
    use super::{command_paths, imports_history, looks_generated, segments};
    use std::path::Path;

    #[test]
    fn paths_are_taken_from_redirects_and_arguments() {
        let dir = std::env::temp_dir().join(format!("comment-guard-post-{}", std::process::id()));
        let _ = std::fs::create_dir_all(&dir);
        let file = dir.join("out.py");
        let _ = std::fs::write(&file, "x = 1\n");
        let command = format!("printf '# a\\n' > {} && sed -i '' 1d notes.md missing.py", file.display());
        let found = command_paths(&command, &dir);
        assert_eq!(found, vec![file.clone()]);
        let relative = command_paths("echo hi >out.py", &dir);
        assert_eq!(relative, vec![file]);
        assert!(command_paths("ls -la", Path::new("/")).is_empty());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn commands_are_split_by_the_shell_rules_that_matter() {
        let parts = segments("git merge -m 'a; b && c' x && cd \"/p q\"; ls").expect("parsed");
        assert_eq!(parts.len(), 3);
        assert_eq!(parts[0], vec!["git", "merge", "-m", "a; b && c", "x"]);
        assert_eq!(parts[1], vec!["cd", "/p q"]);
        assert!(segments("echo a > b").is_none());
        assert!(segments("echo $(date)").is_none());
        assert!(segments("echo \"$(date)\"").is_none());
        assert!(segments("echo `date`").is_none());
        assert!(segments("echo 'unterminated").is_none());
        assert!(segments("echo '$(date) > x'").is_some());
        assert_eq!(segments("git log | head -3").expect("parsed").len(), 2);
    }

    #[test]
    fn commands_that_import_commits_are_recognised() {
        for command in [
            "git merge upstream/main",
            "git -C /x/y pull --ff-only",
            "cd /x && git checkout -- a.py",
            "git fetch && git merge FETCH_HEAD",
            "GIT_EDITOR=true git merge --no-edit x",
            "git stash pop",
            "git merge -m 'integrate; keep tests' upstream",
            "git -c user.name=x merge y",
            "git rebase main && git status",
            "git checkout feature && git log --oneline | head -3",
        ] {
            assert!(imports_history(command), "{command}");
        }
        for command in [
            "git status",
            "git add -A && git commit -m x",
            "git log | head -3",
            "git -c core.hooksPath=/tmp/h checkout a.py",
            "git -c alias.x=!sh checkout a.py",
            "git --git-dir=/x merge y",
            "git --work-tree=/x merge y",
            "git submodule foreach 'echo hi'",
            "git checkout-index -f a.py",
            "git read-tree HEAD",
            "git update-index --add a.py",
            "git merge x && sed -i 1d a.py",
            "git merge x && printf a > b.py",
            "git apply fix.patch",
            "git am mail.patch",
            "git rebase -x 'sed -i 1d a.py' main",
            "git rebase --exec 'make' main",
            "git log > out.txt",
            "git merge $(cat ref)",
            "git merge \"$(cat ref)\"",
            "cat <<EOF | git merge",
            "python3 gen.py",
            "git filter-branch --tree-filter x",
            "git bisect run ./t.sh",
            "ls",
            "",
            "cd /x",
        ] {
            assert!(!imports_history(command), "{command}");
        }
    }

    #[test]
    fn generated_headers_are_recognised() {
        assert!(looks_generated("// Code generated by protoc. DO NOT EDIT.\npackage x\n"));
        assert!(looks_generated("# @generated\nx = 1\n"));
        assert!(!looks_generated("x = 1\ny = 2\n"));
    }
}
