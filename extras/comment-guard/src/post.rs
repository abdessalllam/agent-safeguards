pub fn judge_command(payload: &Map<String, Value>, ledger: &Ledger, trim: bool) -> Verdict {
    let deadline = Instant::now() + TOTAL_TIME;
    if payload.get("cwd").and_then(Value::as_str).is_none() {
        return Verdict::Allow;
    }
    let cwd = crate::base_of(payload);
    if !cwd.is_dir() {
        return Verdict::Allow;
    }
    let command = command_of(payload);
    let key = identity(&cwd);
    let since = payload
        .get("tool_use_id")
        .and_then(Value::as_str)
        .and_then(|id| ledger.take_start(id))
        .or_else(|| ledger.last_check(&key))
        .or_else(|| SystemTime::now().checked_sub(FIRST_WINDOW))
        .unwrap_or(SystemTime::UNIX_EPOCH);
    ledger.mark_check(&key);
    let importing = imports_history(command);
    let (named, folders) = command_targets(command, &cwd, NAMED_PATHS, deadline);
    let (mut files, quiet): (Vec<PathBuf>, Vec<PathBuf>) = named.into_iter().partition(|path| changed_since(path, since));
    let room = MAX_CANDIDATES.saturating_sub(files.len());
    files.extend(walk_files(&cwd, room, deadline, &|meta| modified_since(meta, since)));
    for folder in folders.into_iter().filter(|_| !quiet_command(command)) {
        let room = MAX_CANDIDATES.saturating_sub(files.len());
        files.extend(walk_files(&folder, room, deadline, &|meta| modified_since(meta, since)));
    }
    files.extend(quiet.into_iter().take(MAX_CANDIDATES));
    let mut seen: HashSet<PathBuf> = HashSet::new();
    let mut changes: Vec<Change> = Vec::new();
    for file in files {
        if Instant::now() >= deadline {
            break;
        }
        if !seen.insert(file.clone()) {
            continue;
        }
        if importing {
            rebaseline(&file, since, ledger);
            continue;
        }
        if let Some(change) = change_for(&file, since, ledger, deadline) {
            changes.push(change);
        }
    }
    let born = changes.iter().any(|change| change.baseline.is_none());
    if born {
        drop_copies(&mut changes, command, &cwd, since, ledger);
    }
    let mut verdict = evaluate_after(&changes);
    if verdict.is_some() {
        drop_marked(&mut changes, &cwd);
        if !born {
            drop_copies(&mut changes, command, &cwd, since, ledger);
        }
        verdict = evaluate_after(&changes);
    }
    let Some(reason) = verdict else {
        return Verdict::Allow;
    };
    if !trim {
        return Verdict::Deny(reason);
    }
    let mut notes: Vec<String> = Vec::new();
    let mut left: Vec<Change> = Vec::new();
    for change in changes {
        if evaluate(std::slice::from_ref(&change)).is_none() {
            continue;
        }
        match trim_on_disk(&change, &cwd, ledger) {
            Some(note) => notes.push(note),
            None => left.push(change),
        }
    }
    match (evaluate_after(&left), notes.is_empty()) {
        (Some(rest), true) => Verdict::Deny(rest),
        (Some(rest), false) => Verdict::Deny(format!("{rest} {}", notes.join(" "))),
        (None, true) => Verdict::Deny(reason),
        (None, false) => Verdict::Trimmed {
            input: Value::Null,
            note: notes.join(" "),
        },
    }
}

fn trim_on_disk(change: &Change, cwd: &Path, ledger: &Ledger) -> Option<String> {
    let path = Path::new(&change.file);
    let lang = language_for_file(&change.file)?;
    let inside = fs::canonicalize(path).ok()?.starts_with(fs::canonicalize(cwd).ok()?);
    let meta = fs::symlink_metadata(path).ok()?;
    if !inside || !meta.is_file() {
        return None;
    }
    let cut = trimmed(change)?;
    if fs::read(path).ok()? != change.new.as_bytes() {
        return None;
    }
    let name = path.file_name()?.to_string_lossy().into_owned();
    let temp = path.with_file_name(format!(".{name}.comment-guard-{}", std::process::id()));
    let written = fs::write(&temp, cut.text.as_bytes()).is_ok() && fs::set_permissions(&temp, meta.permissions()).is_ok();
    if !written || fs::rename(&temp, path).is_err() {
        let _ = fs::remove_file(&temp);
        return None;
    }
    let comments = comment_lines(&cut.text, lang);
    ledger.accept(&identity(path), &[seen_of(&cut.text, &comments)]);
    Some(crate::trimmed_note("comment_guard.trimmed_after", &change.file, &cut.removed))
}

fn command_of(payload: &Map<String, Value>) -> &str {
    payload
        .get("tool_input")
        .and_then(|input| input.get("command"))
        .and_then(Value::as_str)
        .unwrap_or("")
}

pub fn refresh_named(payload: &Map<String, Value>, ledger: &Ledger) {
    let cwd = crate::base_of(payload);
    let deadline = Instant::now() + REFRESH_TIME;
    let mut targets: Vec<PathBuf> = Vec::new();
    let mut listed: HashSet<PathBuf> = HashSet::new();
    let mut direct: HashSet<PathBuf> = HashSet::new();
    let quiet = quiet_command(command_of(payload));
    for token in command_tokens(command_of(payload), &cwd, NAMED_PATHS, deadline) {
        let files = source_files(&token, deadline);
        if token.is_file() || !quiet {
            direct.extend(files.iter().cloned());
        }
        for file in files {
            if listed.len() < NAMED_PATHS * 2 && listed.insert(file.clone()) {
                targets.push(file);
            }
        }
    }
    let mut recorded = 0usize;
    for path in targets {
        if Instant::now() >= deadline {
            break;
        }
        let name = path.to_string_lossy().into_owned();
        let Some(lang) = language_for_file(&name) else {
            continue;
        };
        let id = identity(&path);
        let known = ledger.read(&id).is_some();
        if !known && (!direct.contains(&path) || recorded >= NAMED_RECORDS) {
            continue;
        }
        let Some(current) = read_source(&path) else {
            continue;
        };
        let comments = comment_lines(&current, lang);
        let state = seen_of(&current, &comments);
        if !known {
            recorded = recorded.saturating_add(1);
            ledger.baseline_for(&id, state, || comments);
            continue;
        }
        if !ledger.knows(&id, state) {
            ledger.rebaseline_soon(&id, comments, state);
        }
    }
}

fn home() -> Option<PathBuf> {
    let path = PathBuf::from(std::env::var("HOME").ok()?);
    path.is_absolute().then_some(path)
}

fn wildcard_match(pattern: &[char], name: &[char]) -> bool {
    let (mut p, mut n) = (0usize, 0usize);
    let mut star: Option<(usize, usize)> = None;
    while n < name.len() {
        match pattern.get(p) {
            Some('*') => {
                star = Some((p, n));
                p += 1;
            }
            Some('?') => {
                p += 1;
                n += 1;
            }
            Some(c) if Some(c) == name.get(n) => {
                p += 1;
                n += 1;
            }
            _ => match star {
                Some((star_at, matched)) => {
                    p = star_at + 1;
                    n = matched + 1;
                    star = Some((star_at, matched + 1));
                }
                None => return false,
            },
        }
    }
    while pattern.get(p) == Some(&'*') {
        p += 1;
    }
    p == pattern.len()
}

type Listings = HashMap<PathBuf, Vec<(Vec<char>, PathBuf)>>;

fn listing<'a>(cache: &'a mut Listings, dir: &Path) -> &'a [(Vec<char>, PathBuf)] {
    cache.entry(dir.to_path_buf()).or_insert_with(|| {
        let Ok(entries) = fs::read_dir(dir) else {
            return Vec::new();
        };
        entries
            .flatten()
            .take(LISTING_ENTRIES)
            .filter_map(|entry| {
                let name = entry.file_name().to_string_lossy().into_owned();
                (!name.starts_with('.')).then(|| (name.chars().collect(), entry.path()))
            })
            .collect()
    })
}

fn expand_glob(cwd: &Path, word: &str, cache: &mut Listings, room: usize) -> Vec<PathBuf> {
    let (folder, last) = match word.rsplit_once('/') {
        Some((folder, last)) => (folder, last),
        None => ("", word),
    };
    if folder.contains(['*', '?']) {
        return Vec::new();
    }
    let dir = if folder.is_empty() { cwd.to_path_buf() } else { resolve(cwd, folder) };
    let pattern: Vec<char> = last.chars().collect();
    listing(cache, &dir)
        .iter()
        .filter(|(name, _)| wildcard_match(&pattern, name))
        .map(|(_, path)| path.clone())
        .take(room)
        .collect()
}

fn shell_words(command: &str) -> Vec<String> {
    let mut words: Vec<String> = Vec::new();
    let mut word = String::new();
    let mut open = false;
    let mut quote: Option<char> = None;
    let mut chars = command.chars();
    while let Some(c) = chars.next() {
        if let Some(q) = quote {
            if c == q {
                quote = None;
            } else if c == '\\' && q == '"' {
                if let Some(next) = chars.next() {
                    word.push(next);
                }
            } else {
                word.push(c);
            }
            continue;
        }
        match c {
            '\'' | '"' => {
                quote = Some(c);
                open = true;
            }
            '\\' => {
                if let Some(next) = chars.next() {
                    word.push(next);
                    open = true;
                }
            }
            separator if separator.is_whitespace() || ";&|<>()`".contains(separator) => {
                if open {
                    words.push(std::mem::take(&mut word));
                    open = false;
                }
            }
            other => {
                word.push(other);
                open = true;
            }
        }
    }
    if open {
        words.push(word);
    }
    words
}

fn command_words(command: &str) -> Vec<String> {
    let mut words = shell_words(command);
    let separators = |c: char| c.is_whitespace() || "\"'`<>|;&()=,{}[]".contains(c);
    words.extend(command.split(separators).map(str::to_owned));
    let mut seen: HashSet<String> = HashSet::new();
    words.retain(|word| seen.insert(word.clone()));
    words
}

fn assignments(command: &str) -> HashMap<String, String> {
    let mut vars: HashMap<String, String> = HashMap::new();
    for word in shell_words(command) {
        let Some((name, value)) = word.split_once('=') else {
            continue;
        };
        let plain = name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        if name.is_empty() || !plain || name.starts_with(|c: char| c.is_ascii_digit()) {
            continue;
        }
        let value = expand_vars(value, &vars).unwrap_or_else(|| value.to_owned());
        vars.insert(name.to_owned(), value);
    }
    vars
}

fn expand_vars(word: &str, vars: &HashMap<String, String>) -> Option<String> {
    if !word.contains('$') {
        return None;
    }
    let chars: Vec<char> = word.chars().collect();
    let mut out = String::new();
    let mut at = 0usize;
    while let Some(&c) = chars.get(at) {
        if c != '$' {
            out.push(c);
            at = at.saturating_add(1);
            continue;
        }
        let braced = chars.get(at.saturating_add(1)) == Some(&'{');
        let from = at.saturating_add(if braced { 2 } else { 1 });
        let name: String = chars
            .iter()
            .skip(from)
            .take_while(|c| c.is_ascii_alphanumeric() || **c == '_')
            .collect();
        let end = from.saturating_add(name.chars().count());
        if name.is_empty() || (braced && chars.get(end) != Some(&'}')) {
            return None;
        }
        let value = vars.get(&name).cloned().or_else(|| std::env::var(&name).ok())?;
        out.push_str(&value);
        at = end.saturating_add(usize::from(braced));
    }
    Some(out)
}

fn search_bases(command: &str, cwd: &Path, vars: &HashMap<String, String>) -> Vec<PathBuf> {
    let mut bases = vec![cwd.to_path_buf()];
    let mut examined = 0usize;
    for pair in shell_words(command).windows(2) {
        let (Some(first), Some(target)) = (pair.first(), pair.get(1)) else {
            continue;
        };
        if !matches!(first.as_str(), "cd" | "pushd") || target.starts_with('-') {
            continue;
        }
        examined = examined.saturating_add(1);
        if examined > CD_WORDS {
            break;
        }
        let target = expand_vars(target, vars).unwrap_or_else(|| target.clone());
        let path = match (target.strip_prefix("~/"), home()) {
            (Some(rest), Some(root)) => root.join(rest),
            _ => resolve(cwd, &target),
        };
        if path.is_dir() && !bases.contains(&path) && bases.len() < MAX_BASES {
            bases.push(path);
        }
    }
    bases
}

fn command_tokens(command: &str, cwd: &Path, limit: usize, deadline: Instant) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    let mut cache = Listings::new();
    let mut globs = 0usize;
    let vars = assignments(command);
    let bases = search_bases(command, cwd, &vars);
    out.extend(bases.iter().skip(1).cloned());
    let mut words = command_words(command);
    let expanded: Vec<String> = words.iter().filter_map(|word| expand_vars(word, &vars)).collect();
    words.extend(expanded);
    for word in words {
        if out.len() >= limit || Instant::now() >= deadline {
            break;
        }
        let glob = word.contains(['*', '?']);
        if word.chars().all(|c| c == '.') || (word.len() < 2 && !glob) {
            continue;
        }
        if glob {
            globs = globs.saturating_add(1);
            if globs <= GLOB_WORDS {
                for base in &bases {
                    out.extend(expand_glob(base, &word, &mut cache, limit.saturating_sub(out.len())));
                }
            }
        } else {
            for base in &bases {
                let path = match (word.strip_prefix("~/"), home()) {
                    (Some(rest), Some(root)) => root.join(rest),
                    _ => resolve(base, &word),
                };
                if path.exists() {
                    out.push(path);
                }
                if word.starts_with('/') || word.starts_with("~/") {
                    break;
                }
            }
        }
    }
    out
}

fn command_targets(command: &str, cwd: &Path, limit: usize, deadline: Instant) -> (Vec<PathBuf>, Vec<PathBuf>) {
    let tokens = command_tokens(command, cwd, limit, deadline);
    let folders: Vec<PathBuf> = tokens
        .iter()
        .filter(|path| path.is_dir() && !cwd.starts_with(path) && !path.starts_with(cwd))
        .take(NAMED_DIRS)
        .cloned()
        .collect();
    let files = tokens
        .into_iter()
        .filter(|path| path.is_file() && language_for_file(&path.to_string_lossy()).is_some())
        .collect();
    (files, folders)
}

fn modified_since(meta: &fs::Metadata, since: SystemTime) -> bool {
    meta.modified().is_ok_and(|modified| modified >= since)
}

fn walk_files(root: &Path, limit: usize, deadline: Instant, keep: &dyn Fn(&fs::Metadata) -> bool) -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = Vec::new();
    if root.parent().is_none() || home().as_deref() == Some(root) {
        return files;
    }
    let start = Instant::now();
    let mut stack = vec![root.to_path_buf()];
    let mut visited = 0usize;
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            visited = visited.saturating_add(1);
            if visited > WALK_ENTRIES || start.elapsed() > WALK_TIME || Instant::now() >= deadline || files.len() >= limit {
                return files;
            }
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if name.starts_with('.') {
                continue;
            }
            let Ok(kind) = entry.file_type() else {
                continue;
            };
            if kind.is_dir() {
                if !SKIP_DIRS.iter().any(|skip| *skip == &*name) {
                    stack.push(entry.path());
                }
            } else if kind.is_file()
                && entry.metadata().is_ok_and(|meta| keep(&meta))
                && language_for_file(&entry.path().to_string_lossy()).is_some()
            {
                files.push(entry.path());
            }
        }
    }
    files
}

fn source_files(path: &Path, deadline: Instant) -> Vec<PathBuf> {
    if path.is_file() {
        return if language_for_file(&path.to_string_lossy()).is_some() {
            vec![path.to_path_buf()]
        } else {
            Vec::new()
        };
    }
    if path.is_dir() {
        return walk_files(path, SOURCE_FILES, deadline, &|_| true);
    }
    Vec::new()
}

fn is_copy(known: &HashMap<u64, Vec<String>>, text: &str) -> bool {
    known
        .get(&content_hash(text))
        .is_some_and(|texts| texts.iter().any(|known| known == text))
}

fn drop_copies(changes: &mut Vec<Change>, command: &str, cwd: &Path, since: SystemTime, ledger: &Ledger) {
    let deadline = Instant::now() + COPY_TIME;
    let mut known: HashMap<u64, Vec<String>> = HashMap::new();
    let mut budget = SOURCE_BYTES;
    let mut roots = command_tokens(command, cwd, NAMED_PATHS, deadline);
    if command_words(command).iter().any(|word| word == ".") {
        roots.push(cwd.to_path_buf());
    }
    'roots: for token in roots {
        for file in source_files(&token, deadline) {
            if Instant::now() >= deadline {
                break 'roots;
            }
            if changed_since(&file, since) {
                continue;
            }
            let Some(text) = read_source(&file) else {
                continue;
            };
            if text.len() > budget {
                break 'roots;
            }
            budget = budget.saturating_sub(text.len());
            let same = known.entry(content_hash(&text)).or_default();
            if !same.contains(&text) {
                same.push(text);
            }
        }
    }
    let mut kept: Vec<Change> = Vec::new();
    for change in changes.drain(..) {
        if !is_copy(&known, &change.new) {
            kept.push(change);
            continue;
        }
        if let Some(lang) = language_for_file(&change.file) {
            let comments = comment_lines(&change.new, lang);
            let state = seen_of(&change.new, &comments);
            ledger.rebaseline(&identity(Path::new(&change.file)), comments, state);
        }
    }
    *changes = kept;
}

fn absent(stderr: &str, dir: &Path) -> bool {
    let known = ["exists on disk, but not in", "does not exist in", "invalid object name 'HEAD'"];
    known.iter().any(|message| stderr.contains(message))
        || (stderr.contains("not a git repository")
            && !dir.ancestors().any(|folder| folder.join(".git").exists()))
}

fn head_text(path: &Path, deadline: Instant) -> Head {
    let (Some(dir), Some(name)) = (path.parent(), path.file_name().and_then(|name| name.to_str())) else {
        return Head::Unavailable;
    };
    if !inside_repository(dir) {
        return Head::Missing;
    }
    let spec = format!("HEAD:./{name}");
    let Some(ran) = run_git(dir, &["show", &spec], None, deadline) else {
        return Head::Unavailable;
    };
    if ran.stdout.len() as u64 > MAX_OLD_FILE {
        return Head::Unavailable;
    }
    if ran.success {
        return Head::Found(String::from_utf8_lossy(&ran.stdout).into_owned());
    }
    if absent(&ran.stderr, dir) {
        Head::Missing
    } else {
        Head::Unavailable
    }
}

#[cfg(unix)]
fn status_changed(meta: &fs::Metadata, since: SystemTime) -> bool {
    use std::os::unix::fs::MetadataExt;
    let Ok(secs) = u64::try_from(meta.ctime()) else {
        return false;
    };
    let nanos = u32::try_from(meta.ctime_nsec()).unwrap_or(0);
    SystemTime::UNIX_EPOCH + Duration::new(secs, nanos) >= since
}

#[cfg(not(unix))]
fn status_changed(_meta: &fs::Metadata, _since: SystemTime) -> bool {
    false
}

fn changed_since(path: &Path, since: SystemTime) -> bool {
    let Ok(meta) = fs::metadata(path) else {
        return false;
    };
    modified_since(&meta, since) || status_changed(&meta, since)
}

fn born_since(path: &Path, since: SystemTime) -> bool {
    fs::metadata(path)
        .and_then(|meta| meta.created())
        .is_ok_and(|created| created >= since)
}

fn looks_generated(text: &str) -> bool {
    let head: String = text.lines().take(5).collect::<Vec<&str>>().join("\n").to_lowercase();
    GENERATED.iter().any(|marker| head.contains(marker))
}

fn rebaseline(path: &Path, since: SystemTime, ledger: &Ledger) {
    let name = path.to_string_lossy();
    let Some(lang) = language_for_file(&name) else {
        return;
    };
    let Some(current) = read_source(path) else {
        return;
    };
    let comments = comment_lines(&current, lang);
    let state = seen_of(&current, &comments);
    let id = identity(path);
    if changed_since(path, since) && !ledger.knows(&id, state) {
        ledger.rebaseline(&id, comments, state);
    }
}

fn change_for(path: &Path, since: SystemTime, ledger: &Ledger, deadline: Instant) -> Option<Change> {
    let name = path.to_string_lossy().into_owned();
    let lang = language_for_file(&name)?;
    let current = read_source(path)?;
    if looks_generated(&current) {
        return None;
    }
    let id = identity(path);
    let comments = comment_lines(&current, lang);
    let state = seen_of(&current, &comments);
    let recorded = ledger.read(&id);
    if !changed_since(path, since) {
        if recorded.is_none() {
            ledger.baseline_for(&id, state, || comments.clone());
        }
        return None;
    }
    let change = match recorded {
        Some(baseline) => Some(judged(name, current, baseline)),
        None => match head_text(path, deadline) {
            Head::Found(text) => {
                let baseline = ledger.baseline_for(&id, state, || comment_lines(&text, lang));
                Some(judged(name, current, baseline))
            }
            Head::Unavailable => None,
            Head::Missing if born_since(path, since) => {
                ledger.baseline_for(&id, state, Vec::new);
                Some(Change::whole(name, String::new(), current))
            }
            Head::Missing => {
                ledger.baseline_for(&id, state, || comments.clone());
                None
            }
        },
    };
    ledger.accept(&id, &[state]);
    change
}

fn judged(name: String, current: String, baseline: Vec<String>) -> Change {
    Change {
        file: name,
        old: String::new(),
        new: current,
        baseline: Some(baseline),
        partial: false,
        origin: None,
        carry: 0,
    }
}

fn segments(command: &str) -> Option<Vec<Vec<String>>> {
    let mut out: Vec<Vec<String>> = Vec::new();
    let mut words: Vec<String> = Vec::new();
    let mut word = String::new();
    let mut open = false;
    let mut quote: Option<char> = None;
    let mut chars = command.chars().peekable();
    while let Some(c) = chars.next() {
        if let Some(q) = quote {
            if c == q {
                quote = None;
                continue;
            }
            if q == '"' {
                if c == '\\' {
                    if let Some(next) = chars.next() {
                        word.push(next);
                    }
                    continue;
                }
                if c == '`' || (c == '$' && chars.peek() == Some(&'(')) {
                    return None;
                }
            }
            word.push(c);
            continue;
        }
        match c {
            '\'' | '"' => {
                quote = Some(c);
                open = true;
            }
            '\\' => {
                if let Some(next) = chars.next() {
                    word.push(next);
                    open = true;
                }
            }
            '>' | '<' | '`' => return None,
            '$' if chars.peek() == Some(&'(') => return None,
            '\n' | ';' | '&' | '|' => {
                if open {
                    words.push(std::mem::take(&mut word));
                    open = false;
                }
                if matches!(c, '&' | '|') && chars.peek() == Some(&c) {
                    chars.next();
                }
                if !words.is_empty() {
                    out.push(std::mem::take(&mut words));
                }
            }
            space if space.is_whitespace() => {
                if open {
                    words.push(std::mem::take(&mut word));
                    open = false;
                }
            }
            other => {
                word.push(other);
                open = true;
            }
        }
    }
    if quote.is_some() {
        return None;
    }
    if open {
        words.push(word);
    }
    if !words.is_empty() {
        out.push(words);
    }
    Some(out)
}

fn git_segment(words: &[String]) -> Option<bool> {
    if words
        .iter()
        .any(|word| matches!(word.as_str(), "--exec" | "-x") || word.starts_with("--exec="))
    {
        return None;
    }
    let mut at = 0usize;
    while let Some(word) = words.get(at) {
        match word.as_str() {
            "-C" => at = at.saturating_add(2),
            "-c" => {
                let setting = words.get(at.saturating_add(1))?;
                let key = setting.split('=').next().unwrap_or("").to_ascii_lowercase();
                if !BENIGN_CONFIG.contains(&key.as_str()) {
                    return None;
                }
                at = at.saturating_add(2);
            }
            "--no-pager" | "-P" | "-p" | "--paginate" | "--no-optional-locks" => at = at.saturating_add(1),
            option if option.starts_with('-') => return None,
            subcommand => {
                if IMPORTING.contains(&subcommand) {
                    return Some(true);
                }
                return READ_ONLY.contains(&subcommand).then_some(false);
            }
        }
    }
    None
}

const HARMLESS_VARIABLES: &[&str] = &["LANG", "LANGUAGE", "TERM", "NO_COLOR", "COLUMNS", "LINES", "CLICOLOR", "TZ"];

fn is_name(name: &str) -> bool {
    !name.is_empty() && !name.starts_with(|c: char| c.is_ascii_digit()) && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn quiet_command(command: &str) -> bool {
    let Some(parts) = segments(command) else {
        return false;
    };
    let reads = ["status", "diff", "log", "show", "rev-parse", "branch", "ls-files", "remote"];
    !parts.is_empty()
        && parts.iter().all(|words| {
            let start = words
                .iter()
                .take_while(|word| word.split_once('=').is_some_and(|(name, _)| is_name(name)))
                .count();
            let harmless = |word: &String| {
                let name = word.split('=').next().unwrap_or("");
                HARMLESS_VARIABLES.contains(&name) || name.starts_with("LC_")
            };
            if !words.iter().take(start).all(harmless) {
                return false;
            }
            let words = words.get(start..).unwrap_or(&[]);
            !words.iter().any(|word| word == "--pre" || word.starts_with("--pre="))
                && match words.split_first() {
                    None => true,
                    Some((first, rest)) => {
                        HARMLESS.contains(&first.as_str())
                            || (first == "git"
                                && rest
                                    .iter()
                                    .find(|word| !word.starts_with('-'))
                                    .is_some_and(|sub| reads.contains(&sub.as_str())))
                    }
                }
        })
}

fn imports_history(command: &str) -> bool {
    let Some(parts) = segments(command) else {
        return false;
    };
    let mut importing = false;
    for mut words in parts {
        while words
            .first()
            .is_some_and(|word| word.contains('=') && !word.starts_with('=') && !word.contains('/'))
        {
            words.remove(0);
        }
        let Some((first, rest)) = words.split_first() else {
            continue;
        };
        if first == "git" {
            match git_segment(rest) {
                Some(true) => importing = true,
                Some(false) => {}
                None => return false,
            }
        } else if !HARMLESS.contains(&first.as_str()) {
            return false;
        }
    }
    importing
}

